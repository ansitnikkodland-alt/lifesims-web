const {chromium}=require('playwright-core');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('dialog',d=>d.accept());
 const stamp=Math.random().toString(36).slice(2);
 try{
  await page.goto('http://127.0.0.1:8765/scene/?cloud-test=1',{waitUntil:'domcontentloaded'});
  await page.locator('.topbar').waitFor();
  assert.equal(await page.locator('.topbar #familyOpen').count(),1,'Exactly one account+character entry in header');
  assert.equal(await page.locator('.topbar .stats button:visible').count(),2,'Only XP and Family; no legacy Characters button');
  assert.ok((await page.locator('#familyOpen').innerText()).includes('Семья'));
  const before=await page.evaluate(()=>window.LifeSimsCloud.activeStore());
  assert.equal(before,null);
  await page.locator('#familyOpen').click();
  await page.locator('#cloudDialog').waitFor({state:'visible'});
  const form=page.locator('#cloudDialog form').filter({hasText:'Создать взрослый аккаунт'});
  await form.getByRole('textbox',{name:'Имя'}).fill('Мама тест');
  await form.getByRole('textbox',{name:'Ваш email'}).fill('cloud-test-'+stamp+'@example.net');
  await form.getByRole('textbox',{name:/Пароль не менее/}).fill('LongPassword_Cloud_2026!');
  const parentNavigation=page.waitForEvent('framenavigated',{timeout:20000});
  await form.getByRole('button',{name:'Зарегистрироваться'}).click();
  await parentNavigation;
  await page.waitForFunction(()=>window.LifeSimsCloud?.isActive?.(),null,{timeout:20000});
  await page.waitForFunction(()=>document.querySelector('.topbar .person strong')?.textContent.includes('Мама тест'),null,{timeout:25000});
  const parentStore=await page.evaluate(()=>window.LifeSimsCloud.activeStore());
  assert.ok(parentStore.startsWith('lifesims-cloud-'));
  await page.locator('#familyOpen').click();
  await page.locator('#cloudDialog').waitFor({state:'visible'});
  await page.locator('#cloudNav').getByRole('button',{name:'Участники'}).click();
  const child=page.locator('#cloudDialog form').filter({hasText:'Новый детский аккаунт'});
  await child.getByRole('textbox',{name:'Имя ребёнка'}).fill('Сын тест');
  await child.getByRole('textbox',{name:/Пароль ребёнка/}).fill('ChildPassword_2026!23');
  await child.getByRole('button',{name:'Создать аккаунт ребёнка'}).click();
  await page.waitForFunction(()=>document.querySelector('#cloudStatus')?.textContent.includes('kid_'),null,{timeout:15000});
  const childLogin=(await page.locator('#cloudStatus').innerText()).match(/kid_[0-9a-f]{16}/)?.[0];
  assert.ok(childLogin);
  // Figurine studio is in the same Family dialog and never starts paid processing without explicit consent.
  await page.locator('#cloudNav').getByRole('button',{name:'Фигурка'}).click();
  await page.locator('.figurine-account').waitFor({state:'visible'});
  assert.equal(await page.locator('.figurine-account option').count(),2,'Parent and child selectable');
  assert.equal(await page.getByRole('button',{name:'✨ Создать фигурку по фото'}).isDisabled(),true,'AI generation requires owner-side activation');
  assert.equal(await page.getByRole('button',{name:'📂 Добавить готовую фигурку'}).isDisabled(),false,'Parent can import own prepared figurine');
  assert.equal(await page.locator('.figurine-consent input').isChecked(),false);
  await page.locator('.figurine-account').selectOption({index:1});
  assert.equal(await page.getByRole('button',{name:'📂 Добавить готовую фигурку'}).isDisabled(),true,'Child uploads disabled in temporary database');
  // Parent and child share live cat care; no duplicate per-account pet state.
  await page.locator('#cloudNav').getByRole('button',{name:'Котики'}).click();
  await page.locator('.house-pet-grid').waitFor({state:'visible'});
  assert.equal(await page.locator('.house-pet-grid .house-card').count(),2);
  await page.locator('.house-pet-grid').getByRole('button',{name:'🍽 Покормить'}).first().click();
  await page.waitForFunction(()=>document.querySelector('#cloudBody')?.textContent.includes('История ухода'),null,{timeout:18000});
  await page.locator('#cloudNav').getByRole('button',{name:'Забота'}).click();
  await page.locator('.house-actions').waitFor({state:'visible'});
  await page.locator('.house-actions').getByRole('button',{name:'✓ Покормить'}).click();
  await page.waitForFunction(()=>document.querySelector('#cloudBody')?.textContent.includes('Сегодня и ранее'),null,{timeout:18000});
  await page.locator('#cloudNav').getByRole('button',{name:'Чат'}).click();
  await page.locator('.house-chat-form').waitFor({state:'visible'});
  await page.locator('#cloudNav').getByRole('button',{name:'Места'}).click();
  await page.locator('.house-card').first().waitFor({state:'visible'});
  // Backend has created a separate child account, not another local-only profile.
  const exitNavigation=page.waitForEvent('framenavigated',{timeout:20000});
  await page.getByRole('button',{name:'Выйти из аккаунта'}).click();
  await exitNavigation;
  await page.waitForFunction(()=>!window.LifeSimsCloud?.isActive?.(),null,{timeout:15000});
  await page.locator('#familyOpen').click();
  const login=page.locator('#cloudDialog form').filter({hasText:'Войти в LifeSims'});
  await login.getByRole('textbox',{name:'Email или логин ребёнка'}).fill(childLogin);
  await login.getByRole('textbox',{name:'Пароль',exact:true}).fill('ChildPassword_2026!23');
  const kidNavigation=page.waitForEvent('framenavigated',{timeout:20000});
  await login.getByRole('button',{name:'Войти'}).click();
  await kidNavigation;
  await page.waitForFunction(()=>window.LifeSimsCloud?.isActive?.()&&window.LifeSimsCloud.activeStore().startsWith('lifesims-cloud-'),null,{timeout:15000});
  const kidStore=await page.evaluate(()=>window.LifeSimsCloud.activeStore());
  assert.notEqual(kidStore,parentStore);
  assert.equal(await page.locator('#familyOpen').innerText(),'👨‍👩‍👧 Семья');
  assert.equal(await page.locator('.topbar #familyOpen').count(),1);
  assert.ok((await page.locator('.topbar .person strong').innerText()).includes('Сын тест'));
  await page.locator('#familyOpen').click();
  await page.locator('#cloudNav').getByRole('button',{name:'Котики'}).click();
  await page.locator('.house-pet-grid').waitFor({state:'visible'});
  assert.ok((await page.locator('#cloudBody').innerText()).includes('Мама тест'));
  assert.ok((await page.locator('#cloudBody').innerText()).includes('История ухода'));
  const oauth=await page.evaluate(()=>({google:!!window.LifeSimsGoogleCalendarActions,oura:!!window.LifeSimsOuraSync}));
  assert.equal(oauth.google,false);
  assert.equal(oauth.oura,false);
  console.log('CLOUD FAMILY BROWSER PASS: parent registration, guarded child creation, child own sign-in and distinct save slot.');
  if(errors.length)console.warn('Page errors (unrelated modules possible): '+errors.slice(0,5).join(' | '));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
